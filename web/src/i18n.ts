function mergeTranslations(target: Record<string, unknown>, source: Record<string, unknown>) {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      const nextTarget = target[key] && typeof target[key] === "object" && !Array.isArray(target[key])
        ? target[key] as Record<string, unknown>
        : {};
      target[key] = mergeTranslations(nextTarget, value as Record<string, unknown>);
    } else {
      target[key] = value;
    }
  }
  return target;
}

for (const [language, bundle] of Object.entries(extraResources)) {
  mergeTranslations((resources as Record<string, { translation: Record<string, unknown> }>)[language].translation, bundle.translation as Record<string, unknown>);
}

const initialLanguage = window.localStorage.getItem("muzare-language") ?? "en";

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage,
  fallbackLng: "en",
  returnNull: false,
  returnEmptyString: false,
  missingKeyHandler: (_lng, _ns, key) => {
    if (import.meta.env.DEV) {
      console.warn(`[i18n] Missing translation key: ${key}`);
    }
  },
  parseMissingKeyHandler: (key) => key.split(".").pop()?.replace(/([A-Z])/g, " $1").replace(/^./, (value) => value.toUpperCase()) ?? key,
  interpolation: { escapeValue: false },
});

export default i18n;
