import type { TFunction } from "i18next";

/**
 * Localizes backend record/entity type identifiers ("labourer", "attendance", "voucher",
 * "expenseItems", ...) that arrive as machine keys inside count maps and audit rows on the
 * admin surfaces. Unknown keys fall back to a readable title-cased rendering so new backend
 * entity types never render a raw i18n key.
 */
export function translateRecordType(t: TFunction, raw: string | null | undefined): string {
  if (!raw) return "";
  const key = raw
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[\s-]+/g, "_")
    .toLowerCase();
  const fallback = raw
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replaceAll("_", " ")
    .replace(/^./, (letter) => letter.toUpperCase());
  return t(`adminRecordTypes.${key}`, { defaultValue: fallback });
}

